// Turns the files in "Email Templates/" into src/shared/builtin-templates.ts.
//
// The Worker cannot read files at run time, so the built-in email templates are compiled into the app. To change one, edit
// its .txt file (or add a new one) and run `npm run build:templates`. A test fails if the two ever disagree.
//
// File name (without .txt) = template name. File content = the message body, as HTML.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "Email Templates");
const out = join(root, "src", "shared", "builtin-templates.ts");

/** Line endings are normalized, and the file's own trailing blank lines dropped, so the same text gives the same template. */
const clean = (text) => text.replace(/^﻿/, "").replace(/\r\n?/g, "\n").trim();

/** `Wholesale & Distribution` -> `wholesale-distribution`. Stable: it is how an organization's copy is tied to this one. */
const keyOf = (name) => name.toLowerCase().replace(/&/g, " ").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");

const templates = readdirSync(dir)
  .filter((f) => f.toLowerCase().endsWith(".txt"))
  .sort((a, b) => a.localeCompare(b, "en"))
  .map((f) => {
    const name = f.replace(/\.txt$/i, "").trim();
    return { key: keyOf(name), name, htmlBody: clean(readFileSync(join(dir, f), "utf8")) };
  });

const keys = new Set(templates.map((t) => t.key));
if (keys.size !== templates.length) throw new Error("Two template files make the same key");
for (const t of templates) if (!t.key || !t.htmlBody) throw new Error(`Template "${t.name}" has no key or no content`);

const body = templates.map((t) => `  { key: ${JSON.stringify(t.key)}, name: ${JSON.stringify(t.name)}, htmlBody: ${JSON.stringify(t.htmlBody)} },`).join("\n");
writeFileSync(
  out,
  `// GENERATED by scripts/build-templates.mjs from the files in "Email Templates/". Do not edit by hand:
// change the .txt file and run \`npm run build:templates\`.

export interface BuiltinEmailTemplate {
  /** Stable id of the template, so each organization's copy stays tied to it. */
  key: string;
  name: string;
  /** The message body, as HTML. */
  htmlBody: string;
}

export const BUILTIN_EMAIL_TEMPLATES: readonly BuiltinEmailTemplate[] = [
${body}
];
`,
);
console.log(`Wrote ${templates.length} templates to src/shared/builtin-templates.ts`);
